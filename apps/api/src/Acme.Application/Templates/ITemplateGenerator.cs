using Acme.Application.Common;

namespace Acme.Application.Templates;

/// <summary>An image the poster must be built around.</summary>
/// <param name="Url">Permanent asset URL minted by <see cref="ITemplateAssetService"/>.</param>
/// <param name="Description">
/// What the photograph shows. Optional, but it materially improves layout —
/// the designer places a portrait of a person differently from a shelf of
/// stock, and it cannot see the image itself.
/// </param>
public sealed record TemplateImage(
    string Url,
    double Width,
    double Height,
    string? Description = null);

/// <summary>Where a generated poster's photograph comes from.</summary>
/// <remarks>
/// The same four choices for an administrator and a pharmacy. None of them is
/// ever swapped for another without saying so: an AI photograph that cannot be
/// made is an error, not a stock photo the caller did not pick.
/// </remarks>
public enum PosterPhotoMode
{
    /// <summary>A typographic or geometric design.</summary>
    None,

    /// <summary>
    /// Stock photography: the photo chosen by <see cref="PosterPhoto.StockPhotoId"/>,
    /// or the best match for the design when none was chosen. Copied into our
    /// own storage, never hot-linked.
    /// </summary>
    Stock,

    /// <summary>An image already in template storage, at <see cref="PosterPhoto.AssetUrl"/>.</summary>
    Upload,

    /// <summary>Generated by an image model — only when one is configured.</summary>
    Ai,
}

/// <param name="AssetUrl">For <see cref="PosterPhotoMode.Upload"/>: one of our own asset URLs.</param>
/// <param name="StockPhotoId">For <see cref="PosterPhotoMode.Stock"/>: the photo the user chose, if any.</param>
/// <param name="Description">
/// What the photograph shows (upload) or should show (AI). The designer cannot
/// see an upload, so this is what keeps its placement from being blind.
/// </param>
public sealed record PosterPhoto(
    PosterPhotoMode Mode,
    string? AssetUrl = null,
    string? StockPhotoId = null,
    string? Description = null)
{
    public const int MaxDescriptionLength = 300;

    /// <summary>Why this photo choice cannot be used, or null when it can.</summary>
    /// <param name="isOurAsset">Whether a URL is one of our template assets.</param>
    public string? Problem(Func<string, bool> isOurAsset)
    {
        if (Description is { Length: > MaxDescriptionLength })
            return $"Keep the photo description under {MaxDescriptionLength} characters.";

        return Mode switch
        {
            PosterPhotoMode.Upload when string.IsNullOrWhiteSpace(AssetUrl) =>
                "Upload a photo first, or choose another photo option.",
            // Only our own storage: the designer is never pointed at a URL a
            // caller typed.
            PosterPhotoMode.Upload when !isOurAsset(AssetUrl!) =>
                "That photo was not uploaded here. Upload it again.",
            PosterPhotoMode.Stock when StockPhotoId is { Length: > 0 } id
                && (id.Length > 20 || !id.All(char.IsAsciiDigit)) =>
                "That stock photo could not be found. Choose it again.",
            PosterPhotoMode.Ai when (Description?.Trim().Length ?? 0) < 4 =>
                "Describe the photo you want generated.",
            _ => null,
        };
    }
}

/// <summary>A brief for the AI template designer.</summary>
/// <param name="Photo">Where the photograph comes from. Null is <see cref="PosterPhotoMode.None"/>.</param>
/// <param name="Palette">
/// Ignored by the house-style designer, whose palette is fixed. Kept so that a
/// request carrying it is not refused.
/// </param>
public sealed record GenerateTemplateRequest(
    string Prompt,
    string? Category = null,
    string? Palette = null,
    string? Archetype = null,
    PosterPhoto? Photo = null,
    // Whose uploads a pharmacy photo is read from (SEC-15). Null for the admin
    // designer, whose uploads are gallery assets.
    string? OwnerId = null);

/// <summary>An image stored and ready to design around.</summary>
/// <param name="Source">"ai" or "stock" — which provider supplied it.</param>
/// <param name="Remaining">Further candidates available for "try another".</param>
public sealed record PosterImage(
    string Url,
    double Width,
    double Height,
    string? Description,
    string Source,
    int Remaining)
{
    public TemplateImage ToTemplateImage() => new(Url, Width, Height, Description);
}

/// <summary>
/// A generated design. <see cref="CanvasJson"/> has already passed the
/// generator's print rules, but is deliberately NOT persisted — an
/// administrator previews it and chooses whether to publish.
/// </summary>
/// <param name="Notes">
/// Repair rounds the generator needed. Surfaced so the admin knows the first
/// attempt was corrected and can look a little harder at the result.
/// </param>
/// <param name="PhotoNotes">
/// What happened to the photograph when it was not what was asked for — no
/// stock match, stock unavailable, AI not set up. Kept apart from
/// <paramref name="Notes"/> so neither is mistaken for the other, and shown to
/// whoever asked, so a photo choice is never changed silently.
/// </param>
public sealed record GeneratedTemplate(
    string Name,
    string CanvasJson,
    IReadOnlyList<string> Notes,
    IReadOnlyList<string>? PhotoNotes = null);

public interface ITemplateGenerator
{
    /// <param name="bearerToken">
    /// The caller's own access token, forwarded so ai-service can independently
    /// verify the caller is staff. The API does not mint a service token for
    /// this: a machine credential would let anything that reaches the API spend
    /// model budget, whereas forwarding keeps the identity — and the audit
    /// trail — attached to a real administrator.
    /// </param>
    /// <param name="quotaAssertion">
    /// Proof the API checked a monthly allowance before spending, for callers
    /// who are not staff. Null for the admin path, which ai-service authorises
    /// on the staff role alone. See <c>AiQuotaAssertion</c> for why a forwarded
    /// pharmacist token is not sufficient on its own: ai-service is publicly
    /// reachable, so without this a pharmacy could call it directly and never
    /// meet the allowance.
    /// </param>
    Task<Result<GeneratedTemplate>> GenerateAsync(
        GenerateTemplateRequest request,
        string bearerToken,
        CancellationToken ct,
        string? quotaAssertion = null);

    /// <summary>
    /// Generate a bespoke photograph. Returns the raw bytes for the caller to
    /// store — this deliberately does not touch blob storage itself, so that
    /// asset URLs are minted in exactly one place.
    /// </summary>
    /// <summary>
    /// Produce a photograph for a poster.
    /// </summary>
    /// <param name="offset">
    /// Which candidate to take when the provider is stock search, so the UI can
    /// offer "try another" without re-typing the description. Ignored by AI
    /// generation, which produces a fresh image every time.
    /// </param>
    /// <param name="provider">
    /// "auto" (AI when configured, otherwise stock), "ai" (AI or an error,
    /// never a stock photo instead) or "stock".
    /// </param>
    Task<Result<GeneratedImage>> GenerateImageAsync(
        string description,
        string? aspect,
        int offset,
        string bearerToken,
        CancellationToken ct,
        string provider = "auto");

    /// <summary>Which photo sources this deployment can serve.</summary>
    Task<Result<ImageOptions>> GetImageOptionsAsync(string bearerToken, CancellationToken ct);

    /// <summary>Search stock photography for candidate poster imagery.</summary>
    /// <param name="quotaAssertion">
    /// For a pharmacy caller: proof the API rate-limited this search. The stock
    /// key is shared by every pharmacy, so ai-service will not search for a
    /// non-staff caller without it.
    /// </param>
    Task<Result<IReadOnlyList<StockPhoto>>> SearchStockPhotosAsync(
        string query,
        string? aspect,
        string bearerToken,
        CancellationToken ct,
        string? quotaAssertion = null);

    /// <summary>
    /// Download one stock photo by ID.
    /// </summary>
    /// <remarks>
    /// Takes an ID rather than a URL deliberately. A staff endpoint that
    /// fetches an arbitrary caller-supplied URL is a server-side request
    /// forgery vector — inside a container network that URL could name the
    /// cloud metadata endpoint or an internal admin port. The ID is resolved
    /// against the stock provider's API, so the only URL ever fetched is one
    /// the provider returned.
    /// </remarks>
    Task<Result<GeneratedImage>> FetchStockPhotoAsync(
        string photoId,
        string bearerToken,
        CancellationToken ct);
}

/// <param name="ThumbnailUrl">
/// Provider CDN URL, rendered directly in the picker. Only the photo the user
/// actually chooses is copied into our own storage.
/// </param>
public sealed record StockPhoto(
    string Id,
    string ThumbnailUrl,
    double Width,
    double Height,
    string Photographer,
    string Alt);

/// <param name="Width">
/// Natural pixel size, needed so the designer can place the image without
/// distorting it. Zero when unknown.
/// </param>
/// <param name="Source">"ai" or "stock" — which provider actually supplied it.</param>
/// <param name="Remaining">Further stock candidates available for "try another".</param>
public sealed record GeneratedImage(
    byte[] Data,
    string ContentType,
    double Width = 0,
    double Height = 0,
    string? Description = null,
    string Source = "ai",
    int Remaining = 0);

/// <param name="Ai">An image model is configured, so AI photos can be offered.</param>
/// <param name="Stock">Stock photography is configured.</param>
public sealed record ImageOptions(bool Ai, bool Stock);
