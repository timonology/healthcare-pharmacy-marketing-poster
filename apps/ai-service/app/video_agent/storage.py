def _resolve_connection_string() -> str:
    """Return a connection string that reaches Azurite from inside a
    container.

    The .NET API runs on the host, so `UseDevelopmentStorage=true`
    (which points at `127.0.0.1:10000`) works fine there. Python
    ai-service runs in a container, so `127.0.0.1` is the container
    itself and the SDK gets ECONNREFUSED. We rewrite the string here
    so operators don't need per-service env overrides.

    Order:
      1. If `AzureBlob__ConnectionString` is a full Azure connection
         string with real endpoints, use it verbatim.
      2. If it's `UseDevelopmentStorage=true` or points at 127.0.0.1,
         swap the host to `AZURITE_HOST` (default `azurite`, the
         compose service name).
    """
    raw = get_settings().azure_blob_connection_string or ""
    if not raw:
        raise RuntimeError("AzureBlob__ConnectionString not configured")

    azurite_host = os.getenv("AZURITE_HOST", "azurite")

    # Shortcut → full string pointed at the compose service.
    if raw.strip().lower() == "usedevelopmentstorage=true":
        expanded = (
            "DefaultEndpointsProtocol=http;"
            f"AccountName=devstoreaccount1;"
            f"AccountKey={_AZURITE_KEY};"
            f"BlobEndpoint=http://{azurite_host}:10000/devstoreaccount1;"
            f"QueueEndpoint=http://{azurite_host}:10001/devstoreaccount1;"
            f"TableEndpoint=http://{azurite_host}:10002/devstoreaccount1;"
        )
        log.info(
            "Azure Blob: rewrote UseDevelopmentStorage=true → %s (in-container path)",
            f"http://{azurite_host}:10000/",
        )
        return expanded

    # Explicit 127.0.0.1 → azurite. This catches the case where an
    # operator wrote out the full form but left the host as localhost.
    if "127.0.0.1:10000" in raw or "localhost:10000" in raw:
        rewritten = raw.replace("127.0.0.1", azurite_host).replace(
            "localhost", azurite_host,
        )
        log.info(
            "Azure Blob: rewrote 127.0.0.1/localhost → %s in connection string",
            azurite_host,
        )
        return rewritten

    return raw


def _client() -> BlobServiceClient:
    return BlobServiceClient.from_connection_string(_resolve_connection_string())


def ensure_container() -> None:
    s = get_settings()
    svc = _client()
    try:
        svc.create_container(s.azure_blob_container)
    except Exception as exc:  # noqa: BLE001
        # 409 ContainerAlreadyExists — expected on the second+ run.
        if "ContainerAlreadyExists" not in str(exc):
            log.warning("create_container(%s) failed: %s", s.azure_blob_container, exc)


def download_file(blob_key: str, local_path: Path) -> bool:
    """Fetch a blob to disk. Returns False if it is not there.

    False rather than an exception, because every caller is a refine rebuilding
    what a previous render saved, and a missing artifact is a normal thing to
    find: the blob may predate the field that records it, a lifecycle rule may
    have aged it out, or the upload may have failed on a render that otherwise
    succeeded. All of those mean "regenerate this part", not "stop".

    The one thing it must never do is return True having written nothing — a
    caller would then hand a zero-byte file to ffmpeg and get a failure several
    stages downstream, pointing at the wrong thing.
    """
    s = get_settings()
    try:
        blob = _client().get_blob_client(s.azure_blob_container, blob_key)
        local_path.parent.mkdir(parents=True, exist_ok=True)
        with open(local_path, "wb") as f:
            stream = blob.download_blob()
            stream.readinto(f)
    except Exception as exc:  # noqa: BLE001
        log.info("Blob %s could not be downloaded (%s).", blob_key, exc)
        # A partial file is worse than none: it looks like a success to the
        # caller and fails later, somewhere unrelated.
        local_path.unlink(missing_ok=True)
        return False

    if not local_path.exists() or local_path.stat().st_size == 0:
        log.warning("Blob %s downloaded as an empty file.", blob_key)
        local_path.unlink(missing_ok=True)
        return False

    return True


def upload_file(local_path: Path, blob_key: str, content_type: str) -> None:
    """Upload with idempotent container creation.

    If the container is missing (fresh Azurite, or the `ensure_container`
    call at startup failed because Azurite wasn't ready yet), we catch the
    `ContainerNotFound` on first upload, create it, and retry exactly
    once. Anything past that is a real error and bubbles up.
    """
    s = get_settings()
    svc = _client()
    container = svc.get_container_client(s.azure_blob_container)

    def _do_upload() -> None:
        with open(local_path, "rb") as f:
            container.upload_blob(
                name=blob_key,
                data=f,
                overwrite=True,
                content_settings=ContentSettings(content_type=content_type),
            )

    try:
        _do_upload()
    except Exception as exc:  # noqa: BLE001
        if "ContainerNotFound" not in str(exc):
            raise
        log.warning(
            "Container %s missing — auto-creating and retrying upload",
            s.azure_blob_container,
        )
        try:
            svc.create_container(s.azure_blob_container)
        except Exception as create_exc:  # noqa: BLE001
            if "ContainerAlreadyExists" not in str(create_exc):
                raise
        _do_upload()

    log.info(
        "Uploaded %s → %s (%.1f KB)",
        local_path.name, blob_key, local_path.stat().st_size / 1024,
    )
