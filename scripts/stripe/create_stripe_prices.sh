#!/usr/bin/env bash
#
# Creates prices for the products made by create_stripe_products.sh, then
# prints the env block to paste into the API's configuration.
#
# Separate from the products script because prices are immutable in Stripe —
# you never edit one, you create a new price and point config at it. So this is
# the script you re-run on a price change; the products script is not.
#
# Usage:
#   ./create_stripe_prices.sh              # test mode
#   ./create_stripe_prices.sh --live       # live mode
#
set -euo pipefail
cd "$(dirname "$0")"
# shellcheck source=_lib.sh
source ./_lib.sh

require_stripe_cli
parse_mode "${1:-}"
resolve_api_key

SRC="stripe_products.${MODE_LOWER}.env"
if [[ ! -f "$SRC" ]]; then
  echo "❌ $SRC not found." >&2
  echo "   Run ./create_stripe_products.sh ${LIVE_FLAG} first." >&2
  exit 1
fi
# shellcheck disable=SC1090
source "$SRC"

for var in PRODUCT_STARTER PRODUCT_PRO PRODUCT_CREDITS_10 PRODUCT_CREDITS_25 PRODUCT_CREDITS_50; do
  if [[ -z "${!var:-}" ]]; then
    echo "❌ $SRC is missing $var. Re-run ./create_stripe_products.sh ${LIVE_FLAG}." >&2
    exit 1
  fi
done

echo "🚀 Creating Stripe prices  [$MODE mode]"
echo "=================================================================="
confirm_live

# ---------------------------------------------------------------------------
# Pricing. Amounts are in PENCE — Stripe's smallest currency unit for GBP.
# £7.00 => 700. A factor-of-100 slip here is the most common Stripe mistake,
# so every line states the intended figure.
#
# Yearly = 10x monthly, i.e. two months free. If you change that ratio, update
# the display calculation in apps/web/src/app/pricing/page.tsx to match.
# ---------------------------------------------------------------------------
CURRENCY=gbp

STARTER_MONTHLY_PENCE=700     # £7 / month
STARTER_YEARLY_PENCE=7000     # £70 / year
PRO_MONTHLY_PENCE=2500        # £25 / month
PRO_YEARLY_PENCE=25000        # £250 / year

CREDITS_10_PENCE=900          # £9 one-time
CREDITS_25_PENCE=2000         # £20 one-time
CREDITS_50_PENCE=3500         # £35 one-time

recurring_price() {
  local product="$1" nickname="$2" amount="$3" interval="$4"
  run_stripe price prices create ${LIVE_FLAG:+$LIVE_FLAG} \
    --product="$product" \
    --nickname="$nickname" \
    --currency="$CURRENCY" \
    --unit-amount="$amount" \
    -d "recurring[interval]=$interval"
}

one_time_price() {
  local product="$1" nickname="$2" amount="$3"
  run_stripe price prices create ${LIVE_FLAG:+$LIVE_FLAG} \
    --product="$product" \
    --nickname="$nickname" \
    --currency="$CURRENCY" \
    --unit-amount="$amount"
}

echo ""
echo "Subscriptions"
echo "-------------"
STARTER_MONTHLY=$(recurring_price "$PRODUCT_STARTER" "Starter Monthly" "$STARTER_MONTHLY_PENCE" month)
printf '  ✅ %-24s → %s\n' "Starter monthly (£7)" "$STARTER_MONTHLY"

STARTER_YEARLY=$(recurring_price "$PRODUCT_STARTER" "Starter Yearly" "$STARTER_YEARLY_PENCE" year)
printf '  ✅ %-24s → %s\n' "Starter yearly (£70)" "$STARTER_YEARLY"

PRO_MONTHLY=$(recurring_price "$PRODUCT_PRO" "Pro Monthly" "$PRO_MONTHLY_PENCE" month)
printf '  ✅ %-24s → %s\n' "Pro monthly (£25)" "$PRO_MONTHLY"

PRO_YEARLY=$(recurring_price "$PRODUCT_PRO" "Pro Yearly" "$PRO_YEARLY_PENCE" year)
printf '  ✅ %-24s → %s\n' "Pro yearly (£250)" "$PRO_YEARLY"

echo ""
echo "Credit packs"
echo "------------"
CREDITS_10=$(one_time_price "$PRODUCT_CREDITS_10" "10 credits" "$CREDITS_10_PENCE")
printf '  ✅ %-24s → %s\n' "10 credits (£9)" "$CREDITS_10"

CREDITS_25=$(one_time_price "$PRODUCT_CREDITS_25" "25 credits" "$CREDITS_25_PENCE")
printf '  ✅ %-24s → %s\n' "25 credits (£20)" "$CREDITS_25"

CREDITS_50=$(one_time_price "$PRODUCT_CREDITS_50" "50 credits" "$CREDITS_50_PENCE")
printf '  ✅ %-24s → %s\n' "50 credits (£35)" "$CREDITS_50"

OUT="stripe_prices.${MODE_LOWER}.env"
cat > "$OUT" <<EOF
# Generated by create_stripe_prices.sh — $MODE mode — $(date -u +"%Y-%m-%dT%H:%M:%SZ")
#
# Paste into the API's environment (App Service → Environment variables,
# Railway → Variables, or your root .env for docker-compose).
#
# Note the DOUBLE underscores — that's how .NET maps env vars onto nested
# config. A single underscore will not bind and the setting is ignored.

Stripe__Enabled=true
Stripe__Prices__StarterMonthly=$STARTER_MONTHLY
Stripe__Prices__StarterYearly=$STARTER_YEARLY
Stripe__Prices__ProMonthly=$PRO_MONTHLY
Stripe__Prices__ProYearly=$PRO_YEARLY

Stripe__CreditPacks__0__Key=credits_10
Stripe__CreditPacks__0__PriceId=$CREDITS_10
Stripe__CreditPacks__0__Credits=10
Stripe__CreditPacks__0__DisplayName=10 video credits
Stripe__CreditPacks__0__PriceGbp=9

Stripe__CreditPacks__1__Key=credits_25
Stripe__CreditPacks__1__PriceId=$CREDITS_25
Stripe__CreditPacks__1__Credits=25
Stripe__CreditPacks__1__DisplayName=25 video credits
Stripe__CreditPacks__1__PriceGbp=20

Stripe__CreditPacks__2__Key=credits_50
Stripe__CreditPacks__2__PriceId=$CREDITS_50
Stripe__CreditPacks__2__Credits=50
Stripe__CreditPacks__2__DisplayName=50 video credits
Stripe__CreditPacks__2__PriceGbp=35
EOF

echo ""
echo "=================================================================="
echo "✅ Prices created. Env block written to: $OUT"
echo ""
cat "$OUT"
echo ""
echo "Still needed — these are secrets, so they aren't generated here:"
echo "   Stripe__SecretKey       https://dashboard.stripe.com/${MODE_LOWER/live/}apikeys"
echo "   Stripe__WebhookSecret   from 'stripe listen', or your webhook endpoint"
echo ""
